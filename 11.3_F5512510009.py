import numpy as np

A = np.array([
    [2.01475, -0.020875, 0, 0],
    [-0.020875, 2.01475, -0.020875, 0],
    [0, -0.020875, 2.01475, -0.020875],
    [0, 0, -0.020875, 2.01475]
], dtype=float)

b = np.array([4.175, 0, 0, 2.0875])

x = np.linalg.solve(A, b)

print("Solusi:")
print(x)